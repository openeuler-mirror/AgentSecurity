"""Turn a fully read Python rule into one conservative byte regex."""

from dataclasses import dataclass
import re

from . import prefilter_contract as limits
from .prefilter_contract import RuleSpec
from .regex_subset_parser import Node, UnsupportedPattern, parse_pattern


_ANY = "(?s:.*)"


@dataclass(frozen=True)
class SimplifiedRule:
    expression: str | None
    reason: str


@dataclass(frozen=True)
class _Fragment:
    expression: str
    nullable: bool


def _chars(chars: str, flags: int) -> str:
    values = set(chars)
    if flags & re.I:
        for char in chars:
            if "a" <= char <= "z" or "A" <= char <= "Z":
                values.update((char.lower(), char.upper()))
    escaped = "".join(f"\\x{ord(char):02x}" for char in sorted(values))
    return escaped if len(values) == 1 else "[" + escaped + "]"


class _Generator:
    def __init__(self, flags: int):
        self.flags = flags
        self.nodes = 0
        self.branches = 0

    def visit(self, node: Node) -> _Fragment:
        self.nodes += 1
        if self.nodes > limits.MAX_STRUCTURE_NODES:
            raise UnsupportedPattern("generated node budget exceeded")
        kind = node.kind
        if kind == "literal":
            result = (_Fragment(_chars(node.value, self.flags), False)
                      if ord(node.value) <= 127 else _Fragment(_ANY, True))
        elif kind == "class":
            result = _Fragment(_chars(node.value, self.flags), False)
        elif kind == "any":
            result = _Fragment(_ANY, True)
        elif kind in ("anchor", "assertion", "empty"):
            result = _Fragment("", True)
        elif kind == "group":
            result = self.visit(node.children[0])
        elif kind == "seq":
            parts = [self.visit(child) for child in node.children]
            expression = "".join(part.expression for part in parts)
            while _ANY + _ANY in expression:
                expression = expression.replace(_ANY + _ANY, _ANY)
            result = _Fragment(expression, all(part.nullable for part in parts))
        elif kind == "alt":
            self.branches += len(node.children)
            if self.branches > limits.MAX_STRUCTURE_BRANCHES:
                raise UnsupportedPattern("generated branch budget exceeded")
            parts = [self.visit(child) for child in node.children]
            result = _Fragment("(?:" + "|".join(part.expression for part in parts) + ")",
                               any(part.nullable for part in parts))
        else:  # repeat
            child_node = node.children[0]
            child = self.visit(child_node)
            simple = child_node.kind == "class" or child_node.kind == "literal" and ord(child_node.value) <= 127
            bounded = node.minimum <= 64 and (node.maximum is None or node.maximum <= 64)
            if simple and bounded:
                if node.minimum == node.maximum:
                    suffix = "{" + str(node.minimum) + "}"
                else:
                    suffix = "{" + str(node.minimum) + "," + ("" if node.maximum is None else str(node.maximum)) + "}"
                result = _Fragment(child.expression + suffix, node.minimum == 0)
            elif node.minimum == 0:
                result = _Fragment(_ANY, True)
            else:
                result = _Fragment(child.expression + _ANY, child.nullable)
        if len(result.expression) > limits.MAX_STRUCTURE_BYTES:
            raise UnsupportedPattern("generated byte budget exceeded")
        return result


def simplify_rule(rule: RuleSpec) -> SimplifiedRule:
    """The expression is necessary, or None means this rule stays on Python."""
    try:
        root = parse_pattern(rule.pattern, rule.flags)
        from .prefilter_compat import python_compatibility
        compatibility = python_compatibility()
        if not compatibility.supported:
            return SimplifiedRule(None, "Python regex capability check failed: " + compatibility.reason)
        fragment = _Generator(rule.flags).visit(root)
    except UnsupportedPattern as error:
        return SimplifiedRule(None, str(error))
    if fragment.nullable:
        return SimplifiedRule(None, "nullable simplified expression")
    if not limits.validate_generated_expression(fragment.expression):
        return SimplifiedRule(None, "invalid generated expression")
    return SimplifiedRule(fragment.expression, "simplified expression")
